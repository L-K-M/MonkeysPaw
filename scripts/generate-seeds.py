#!/usr/bin/env python3
"""Embed the eligible seed Markdown as exact UTF-8 in the shared Core target."""

from pathlib import Path


def is_prompt(path: str) -> bool:
    parts = path.split("/")
    return (
        path != "README.md"
        and path.endswith(".md")
        and not any(part.startswith("_") for part in parts)
        and not any(part.startswith(".") for part in parts[:-1])
    )


def swift_string(value: str) -> str:
    escapes = {"\\": "\\\\", '"': '\\"', "\n": "\\n", "\r": "\\r", "\t": "\\t"}
    escaped = "".join(
        escapes.get(char)
        or (f"\\u{{{ord(char):x}}}" if ord(char) < 32 or ord(char) in (127, 0x2028, 0x2029) else char)
        for char in value
    )
    return '"' + escaped + '"'


def main() -> None:
    root = Path(__file__).resolve().parent.parent
    source = root / "seed"
    paths = sorted(
        (path for path in source.rglob("*")
         if path.is_file() and not path.is_symlink() and is_prompt(path.relative_to(source).as_posix())),
        key=lambda path: path.relative_to(source).as_posix().encode("utf-8"),
    )
    lines = [
        "// Generated by scripts/generate-seeds.py. Edit seed/ and regenerate.",
        "import Foundation",
        "",
        "enum SeedCatalog {",
        "    struct Seed {",
        "        let relativePath: String",
        "        let bytes: Data",
        "    }",
        "",
        "    static let prompts: [Seed] = [",
    ]
    for path in paths:
        relative = path.relative_to(source).as_posix()
        text = path.read_bytes().decode("utf-8")
        lines.append(f"        Seed(relativePath: {swift_string(relative)},")
        lines.append(f"             bytes: Data({swift_string(text)}.utf8)),")
    lines += ["    ]", "}", ""]
    destination = root / "Sources/MonkeysPawCore/Domain/SeedCatalog.generated.swift"
    destination.write_bytes("\n".join(lines).encode("utf-8"))


if __name__ == "__main__":
    main()
