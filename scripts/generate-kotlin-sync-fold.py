#!/usr/bin/env python3
"""Port the frozen Swift C/F table without consulting host Unicode data or the network."""

import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "Sources/MonkeysPawCore/Sync/SyncPathCaseFold.swift"
TARGET = ROOT / "android/core/src/main/kotlin/ch/lkmc/monkeyspaw/core/domain/paths/SyncPathCaseFold.kt"


def kotlin_text(swift_text):
    scalars = re.findall(r"\\u\{([0-9A-F]+)\}", swift_text)
    text = "".join(chr(int(scalar, 16)) for scalar in scalars)
    utf16 = text.encode("utf-16-be")
    return "".join(f"\\u{int.from_bytes(utf16[i:i + 2], 'big'):04X}" for i in range(0, len(utf16), 2))


def generate():
    source = SOURCE.read_text(encoding="utf-8")
    ranges = re.findall(
        r"MappingRange\(first: 0x([0-9A-F]+), last: 0x([0-9A-F]+), step: (\d+), delta: (-?\d+)\)", source)
    exceptions = re.findall(r'^\s*0x([0-9A-F]+): "((?:\\u\{[0-9A-F]+\})+)",$', source, re.MULTILINE)
    if not ranges or len(ranges) != source.count("MappingRange(first:"):
        raise SystemExit("Unrecognized Swift range")
    if not exceptions or len(exceptions) != len(re.findall(r"^\s*0x.*:", source, re.MULTILINE)):
        raise SystemExit("Unrecognized Swift exception")
    attribution = "\n".join(line.removeprefix("/// ") for line in source.splitlines() if line.startswith("/// "))
    header = "\n".join(" * " + line for line in attribution.splitlines())
    range_rows = "\n".join(f"        MappingRange(0x{first}, 0x{last}, {step}, {delta}),"
                           for first, last, step, delta in ranges)
    exception_rows = "\n".join(f'        0x{scalar} to "{kotlin_text(text)}",' for scalar, text in exceptions)
    return f'''package ch.lkmc.monkeyspaw.core.domain.paths

/**
{header}
 * Generated by scripts/generate-kotlin-sync-fold.py from SyncPathCaseFold.swift; do not edit.
 */
internal object SyncPathCaseFold {{
    fun fold(text: String): String = buildString {{
        text.codePoints().forEach {{ scalar ->
            val replacement = exceptions[scalar]
            if (replacement != null) {{
                append(replacement)
            }} else {{
                val range = ranges.firstOrNull {{
                    scalar in it.first..it.last && (scalar - it.first) % it.step == 0
                }}
                appendCodePoint(scalar + (range?.delta ?: 0))
            }}
        }}
    }}

    internal data class MappingRange(val first: Int, val last: Int, val step: Int, val delta: Int)

    internal val ranges = listOf(
{range_rows}
    )

    internal val exceptions = mapOf(
{exception_rows}
    )
}}
'''


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if the checked-in port differs")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if not TARGET.exists() or TARGET.read_bytes() != generated.encode("utf-8"):
            raise SystemExit("Kotlin fold table differs; run scripts/generate-kotlin-sync-fold.py")
        print("Kotlin fold table matches the frozen Swift source.")
    else:
        TARGET.write_bytes(generated.encode("utf-8"))
