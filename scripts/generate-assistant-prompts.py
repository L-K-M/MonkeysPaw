#!/usr/bin/env python3
"""Embed exact prompt bytes in Core without a runtime resource bundle."""

import argparse
from pathlib import Path
import sys


def swift_string(value: str) -> str:
    escapes = {"\\": "\\\\", '"': '\\"', "\n": "\\n", "\r": "\\r", "\t": "\\t"}
    escaped = "".join(
        escapes.get(char)
        or (f"\\u{{{ord(char):x}}}" if ord(char) < 32 or ord(char) in (127, 0x2028, 0x2029) else char)
        for char in value
    )
    return '"' + escaped + '"'


def catalog(root: Path) -> bytes:
    source = root / "Assistant/Prompts"
    names = ("write", "review", "improve")
    paths = {path.name for path in source.iterdir()}
    if paths != {f"{name}.md" for name in names}:
        raise SystemExit("Expected exactly write.md, review.md, and improve.md under Assistant/Prompts/")
    lines = [
        "// Generated by scripts/generate-assistant-prompts.py. Edit Assistant/Prompts/ and regenerate.",
        "",
        "public enum AssistantPrompts {",
    ]
    for name in names:
        path = source / f"{name}.md"
        if path.is_symlink() or not path.is_file():
            raise SystemExit("Assistant prompt sources must be regular files, not symlinks")
        prompt = path.read_bytes().decode("utf-8")
        lines.append(f"    public static let {name}: String = {swift_string(prompt)}")
    lines += ["}", ""]
    return "\n".join(lines).encode("utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="Fail if the checked-in catalog is stale")
    mode.add_argument("--stdout", action="store_true", help="Write generated Swift to stdout without changing files")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    generated = catalog(root)
    destination = root / "Sources/MonkeysPawCore/Assistant/AssistantPrompts.generated.swift"
    if args.check:
        if not destination.is_file() or destination.read_bytes() != generated:
            raise SystemExit("Assistant prompt catalog is stale; run scripts/generate-assistant-prompts.py")
    elif args.stdout:
        sys.stdout.buffer.write(generated)
    else:
        destination.write_bytes(generated)


if __name__ == "__main__":
    main()
