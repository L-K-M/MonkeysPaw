#!/usr/bin/env python3
"""Embed exact prompt bytes in Swift and Kotlin without runtime resource bundles."""

import argparse
from pathlib import Path
import sys


NAMES = ("write", "review", "improve")
SWIFT_CATALOG = Path("Sources/MonkeysPawCore/Assistant/AssistantPrompts.generated.swift")
KOTLIN_CATALOG = Path("android/core/src/main/kotlin/ch/lkmc/monkeyspaw/core/llm/AssistantPrompts.generated.kt")


def swift_string(value: str) -> str:
    escapes = {"\\": "\\\\", '"': '\\"', "\n": "\\n", "\r": "\\r", "\t": "\\t"}
    escaped = "".join(
        escapes.get(char)
        or (f"\\u{{{ord(char):x}}}" if ord(char) < 32 or ord(char) in (127, 0x2028, 0x2029) else char)
        for char in value
    )
    return '"' + escaped + '"'


def kotlin_string(value: str) -> str:
    escapes = {"\\": "\\\\", '"': '\\"', "$": "\\$", "\n": "\\n", "\r": "\\r", "\t": "\\t"}
    escaped = []
    for char in value:
        scalar = ord(char)
        if char in escapes:
            escaped.append(escapes[char])
        elif scalar < 32 or scalar in (127, 0x2028, 0x2029):
            escaped.append(f"\\u{scalar:04x}")
        elif scalar > 0xffff:
            # Kotlin's Unicode escapes encode UTF-16 code units.
            scalar -= 0x10000
            escaped.append(f"\\u{0xd800 + (scalar >> 10):04x}\\u{0xdc00 + (scalar & 0x3ff):04x}")
        else:
            escaped.append(char)
    return '"' + "".join(escaped) + '"'


def read_prompts(root: Path) -> dict[str, str]:
    source = root / "Assistant/Prompts"
    if not source.is_dir():
        raise SystemExit(f"Missing prompt source directory: {source}")
    paths = {path.name for path in source.iterdir()}
    if paths != {f"{name}.md" for name in NAMES}:
        raise SystemExit("Expected exactly write.md, review.md, and improve.md under Assistant/Prompts/")
    prompts = {}
    for name in NAMES:
        path = source / f"{name}.md"
        if path.is_symlink() or not path.is_file():
            raise SystemExit("Assistant prompt sources must be regular files, not symlinks")
        try:
            prompts[name] = path.read_bytes().decode("utf-8")
        except UnicodeDecodeError as error:
            raise SystemExit(f"{path} is not valid UTF-8; save the prompt as UTF-8: {error}") from error
    return prompts


def swift_catalog(prompts: dict[str, str]) -> bytes:
    lines = [
        "// Generated by scripts/generate-assistant-prompts.py. Edit Assistant/Prompts/ and regenerate.",
        "",
        "public enum AssistantPrompts {",
    ]
    for name in NAMES:
        lines.append(f"    public static let {name}: String = {swift_string(prompts[name])}")
    lines += ["}", ""]
    return "\n".join(lines).encode("utf-8")


def kotlin_catalog(prompts: dict[str, str]) -> bytes:
    lines = [
        "// Generated by scripts/generate-assistant-prompts.py. Edit Assistant/Prompts/ and regenerate.",
        "package ch.lkmc.monkeyspaw.core.llm",
        "",
        "internal object AssistantPrompts {",
    ]
    for name in NAMES:
        lines.append(f"    val {name}: String = {kotlin_string(prompts[name])}")
    lines += ["}", ""]
    return "\n".join(lines).encode("utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="Fail if either checked-in catalog is stale")
    mode.add_argument("--stdout", action="store_true", help="Write generated Swift to stdout without changing files")
    args = parser.parse_args()
    root = Path(__file__).resolve().parent.parent
    prompts = read_prompts(root)
    swift = swift_catalog(prompts)
    if args.stdout:
        sys.stdout.buffer.write(swift)
        return

    catalogs = {SWIFT_CATALOG: swift, KOTLIN_CATALOG: kotlin_catalog(prompts)}
    if args.check:
        stale = [str(path) for path, generated in catalogs.items()
                 if not (root / path).is_file() or (root / path).read_bytes() != generated]
        if stale:
            raise SystemExit("Assistant prompt catalogs are stale:\n" + "\n".join(stale)
                             + "\nRun scripts/generate-assistant-prompts.py")
        return

    for path, generated in catalogs.items():
        destination = root / path
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_bytes(generated)


if __name__ == "__main__":
    main()
