#!/usr/bin/env python3
"""Generate search NFC and Swift 16-to-17 property additions from verified UCD files."""

import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "Sources/MonkeysPawCore/Domain/Library/SearchUnicodeData.swift"
FILES = {
    "UnicodeData.txt": "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c",
    "DerivedNormalizationProps.txt": "71fd6a206a2c0cdd41feb6b7f656aa31091db45e9cedc926985d718397f9e488",
    "GraphemeBreakProperty.txt": "d6b51d1d2ae5c33b451b7ed994b48f1f4dc62b2272a5831e7fd418514a6bae89",
    "UnicodeData16.txt": "ff58e5823bd095166564a006e47d111130813dcf8bf234ef79fa51a870edb48f",
    "GraphemeBreakProperty16.txt": "c29360bd6f7132811d701d29069541e827eb44bfc4c8fbde8c370d6982689dc1",
}


def unicode_data(text):
    result = {}
    for line in text.splitlines():
        fields = line.split(";")
        scalar = int(fields[0], 16)
        if fields[1].endswith(", First>"):
            first = scalar
        elif fields[1].endswith(", Last>"):
            for value in range(first, scalar + 1):
                result[value] = fields
        else:
            result[scalar] = fields
    return result


def properties(text, wanted=None):
    result = {}
    for line in text.splitlines():
        content = line.split("#")[0].strip()
        if not content:
            continue
        bounds, prop, *_ = map(str.strip, content.split(";"))
        if wanted is not None and prop != wanted:
            continue
        bounds = bounds.split("..")
        for scalar in range(int(bounds[0], 16), int(bounds[-1], 16) + 1):
            result[scalar] = prop
    return result


def ranges(values):
    result = []
    for scalar, value in sorted(values.items()):
        if result and scalar == result[-1][1] + 1 and value == result[-1][2]:
            result[-1][1] = scalar
        else:
            result.append([scalar, scalar, value])
    return result


def generate(files):
    data = unicode_data(files["UnicodeData.txt"])
    previous = unicode_data(files["UnicodeData16.txt"])
    decompositions = {scalar: [int(part, 16) for part in fields[5].split()]
                      for scalar, fields in data.items() if fields[5] and not fields[5].startswith("<")}

    def expand(scalar):
        return [part for next_scalar in decompositions.get(scalar, [scalar])
                for part in (expand(next_scalar) if next_scalar != scalar else [scalar])]

    exclusions = properties(files["DerivedNormalizationProps.txt"], "Full_Composition_Exclusion")
    compositions = {(parts[0] << 21) | parts[1]: scalar for scalar, parts in decompositions.items()
                    if len(parts) == 2 and scalar not in exclusions}
    assert len(compositions) == sum(len(parts) == 2 and scalar not in exclusions
                                    for scalar, parts in decompositions.items())
    classes = {scalar: int(fields[3]) for scalar, fields in data.items() if int(fields[3]) != 0}
    additions = {scalar: 1 for scalar, fields in data.items()
                 if fields[2][0] in "LMN" and previous.get(scalar, ["", "", "Cn"])[2][0] not in "LMN"}
    assert all(fields[2][0] not in "LMN" or data[scalar][2][0] in "LMN"
               for scalar, fields in previous.items())
    before = properties(files["GraphemeBreakProperty16.txt"])
    after = properties(files["GraphemeBreakProperty.txt"])
    # Only these additions affect the grapheme boundaries around whitespace and #.
    representatives = {"Extend": 0x0300, "SpacingMark": 0x0903}
    changed = {scalar: representatives[prop] for scalar, prop in after.items()
               if prop != before.get(scalar, "Other")}
    assert all(scalar not in previous for scalar in changed)

    result = [
        "/// Generated by scripts/generate-search-unicode.py; do not edit.",
        "/// Unicode 17.0.0 NFC data and additions to Swift 6.2's Unicode 16 tables.",
        "/// Sources: https://www.unicode.org/Public/{17,16}.0.0/ucd/",
        "/// File SHA-256 values are pinned in the generator.",
        "/// © 2025 Unicode, Inc. Unicode License v3: docs/licenses/UNICODE.txt.",
        "enum SearchUnicodeData {",
        "    static let decompositions: [UInt32: [UInt32]] = [",
    ]
    for scalar in sorted(decompositions):
        parts = ", ".join(f"0x{part:X}" for part in expand(scalar))
        result.append(f"        0x{scalar:X}: [{parts}],")
    result += ["    ]", "", "    static let compositions: [UInt64: UInt32] = ["]
    for pair, scalar in sorted(compositions.items()):
        result.append(f"        0x{pair:X}: 0x{scalar:X},")
    result += ["    ]", "", "    static let combiningClasses: [(first: UInt32, last: UInt32, value: UInt8)] = ["]
    for first, last, value in ranges(classes):
        result.append(f"        (0x{first:X}, 0x{last:X}, {value}),")
    result += ["    ]", "", "    static let wordAdditions: [ClosedRange<UInt32>] = ["]
    for first, last, _ in ranges(additions):
        result.append(f"        0x{first:X}...0x{last:X},")
    result += ["    ]", "", "    static let graphemeAdditions: [(range: ClosedRange<UInt32>, representative: UInt32)] = ["]
    for first, last, value in ranges(changed):
        result.append(f"        (0x{first:X}...0x{last:X}, 0x{value:X}),")
    result += ["    ]", "}", ""]
    return "\n".join(result)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ucd-dir", type=Path, required=True,
                        help="Directory with the five named Unicode 17/16 source files")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    files = {}
    for name, digest in FILES.items():
        content = (args.ucd_dir / name).read_bytes()
        if hashlib.sha256(content).hexdigest() != digest:
            raise SystemExit(f"Wrong UCD SHA-256: {name}")
        files[name] = content.decode("utf-8")
    generated = generate(files).encode("utf-8")
    if args.check:
        if not TARGET.exists() or TARGET.read_bytes() != generated:
            raise SystemExit("Search Unicode data differs; rerun the generator")
        print("Search Unicode data matches the verified Unicode 17/16 sources.")
    else:
        TARGET.write_bytes(generated)
