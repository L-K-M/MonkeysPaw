package ch.lkmc.monkeyspaw.core.sync

import ch.lkmc.monkeyspaw.core.domain.ULID
import ch.lkmc.monkeyspaw.core.domain.format.*
import ch.lkmc.monkeyspaw.core.domain.paths.SyncPathValidator
import ch.lkmc.monkeyspaw.core.domain.sync.*
import ch.lkmc.monkeyspaw.core.services.LibraryPath
import ch.lkmc.monkeyspaw.core.services.SyncLibraryFile
import ch.lkmc.monkeyspaw.core.services.SyncMutationOrigin

internal sealed class SyncConflictMetadataError private constructor() : Exception("Invalid sync metadata.", null, false, true) {
    data object InvalidPrompt : SyncConflictMetadataError()
    data object InvalidOrigin : SyncConflictMetadataError()
    final override fun toString(): String = "<sync metadata error>"
}

/** Private content markers are independent of server WriteOrigin and assistant provenance. */
internal object SyncConflictMetadata {
    const val conflictKey = "x-monkeyspaw-conflict-of"
    const val rescuedKey = "x-monkeyspaw-rescued"

    fun origin(document: PromptDocument): SyncPromptOrigin? {
        if (!document.canRender) throw SyncConflictMetadataError.InvalidPrompt
        if (SyncMutationOrigin.hasInvalidOrigin(document)) throw SyncConflictMetadataError.InvalidOrigin
        return SyncMutationOrigin.origin(document)
    }

    /** Validate group markers too, but project an origin only for private prompts. */
    fun origin(bytes: ByteArray, filename: String, scope: SyncPathValidator.Scope = SyncPathValidator.Scope.USER): SyncPromptOrigin? {
        val value = origin(PromptCodec.parseFile(bytes, filename))
        return if (scope == SyncPathValidator.Scope.USER) value else null
    }

    fun hasInvalidOrigin(document: PromptDocument): Boolean = SyncMutationOrigin.hasInvalidOrigin(document)

    class Ingest(val origin: SyncPromptOrigin?, val issue: SyncIssueCode?) {
        override fun toString(): String = "<sync marker ingest>"
    }

    /** Malformed unknown markers do not block installation of canonical-valid server bytes. */
    fun ingest(bytes: ByteArray, filename: String, scope: SyncPathValidator.Scope): Ingest = try {
        Ingest(origin(bytes, filename, scope), null)
    } catch (_: SyncConflictMetadataError.InvalidOrigin) {
        Ingest(null, SyncIssueCode.Content(PromptIssueCode.INVALID_METADATA_TYPE))
    }

    fun settingOrigin(origin: SyncPromptOrigin?, bytes: ByteArray, filename: String): ByteArray {
        val document = PromptCodec.parseFile(bytes, filename)
        val existing = origin(document)
        if (origin != null && existing == origin) return bytes.copyOf()
        val keys = setOf(conflictKey, rescuedKey)
        val entries = document.preservedHeader?.entries.orEmpty()
        if (origin == null && entries.none { PortableYaml.string(it.key) in keys }) return bytes.copyOf()
        if (origin is SyncPromptOrigin.ConflictOf && origin.promptID == document.frontMatter.id) {
            throw SyncConflictMetadataError.InvalidOrigin
        }
        val changed = entries.filterNot { PortableYaml.string(it.key) in keys }.toMutableList()
        when (origin) {
            is SyncPromptOrigin.ConflictOf -> changed.add(YamlNode.Entry(YamlNode.Scalar(conflictKey, YamlTag.STR),
                YamlNode.Scalar(origin.promptID.rawValue, YamlTag.STR)))
            SyncPromptOrigin.Rescued -> changed.add(YamlNode.Entry(YamlNode.Scalar(rescuedKey, YamlTag.STR),
                YamlNode.Scalar("true", YamlTag.BOOL)))
            null -> Unit
        }
        val updated = PromptDocument(document.source, document.body, document.frontMatter, document.template,
            document.decodingIssues, YamlNode.Mapping(changed), document.declarationLocations)
        val result = PromptCodec.write(updated).encodeToByteArray(throwOnInvalidSequence = true)
        if (origin(result, filename) != origin) throw SyncConflictMetadataError.InvalidOrigin
        return result
    }

    /** Full regenerated bytes, including the copy's own ID, prove reuse after rename or restart. */
    fun copyBytes(file: SyncLibraryFile, freshID: ULID, origin: SyncPromptOrigin, filename: String): ByteArray {
        val document = PromptCodec.parseFile(file.bytes, LibraryPath.filename(file.path))
        origin(document)
        if (freshID == document.frontMatter.id) throw SyncError.InvalidState
        return SyncMutationOrigin.copyBytes(document, freshID, origin, filename)
    }
}
